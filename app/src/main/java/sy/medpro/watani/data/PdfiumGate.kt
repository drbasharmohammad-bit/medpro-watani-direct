package sy.medpro.watani.data

import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock

/**
 * بوابة التزامن العالمية لمحرّك PDFium (build 1.2.54 — إصلاح
 * كراش القارئ الجذري).
 *
 * الدليل (اختبار أجهزة على محاكي CI، تشغيل 46001293621):
 * التطبيق انهار بـSIGABRT بعد ~2.3 ثانية من فتح كتيّب عربي،
 * ورسالة الإجهاض: «Scudo ERROR: invalid chunk state when
 * deallocating address» — فساد كومة داخل libpdfium.so عند
 * FT_Load_Glyph على خيط خلفي. PDFium/FreeType لا يحتملان
 * نداءات متزامنة غير متزامنة: القارئ كان يرسم الصفحات على
 * خيط الرسم المخصص بينما محرّك النص (PdfiumTextEngine) يمشي
 * على الوثيقة نفسها من Dispatchers.IO بلا أي قفل مشترك،
 * والإغلاق عند مغادرة الشاشة كان يحدث على الخيط الرئيسي
 * بينما المشي النصي جارٍ — فتتصادم التحريرات الأصلية وتفسد
 * الكومة. على جهاز الدكتور الأسرع (رسم عالي الدقة لصفحات
 * كثيرة + فهرسة نصية معًا) صار التصادم شبه حتمي عند كل فتح،
 * وبالمختبر كان سباقًا: نجا تشغيل وانهار آخر.
 *
 * القاعدة بعد هذا الإصلاح: كل دخول أصلي إلى PDFium — فتح،
 * رسم، مشي نصي، فحص صلاحية، إغلاق وثيقة — يمرّ عبر هذه
 * البوابة الواحدة، فلا يتقاطع نداءان أصليان أبدًا مهما كان
 * الخيط الطالب. البوابة قفل تعاوني (Mutex) لأن كل المستهلكين
 * دوال معلّقة أصلًا؛ الإغلاق عند التخلّص يُطلق عبر نطاق IO
 * منفصل يمرّ بالبوابة نفسها (انظر PdfViewerScreen).
 */
object PdfiumGate {
    private val mutex = Mutex()

    suspend fun <T> run(block: suspend () -> T): T = mutex.withLock { block() }
}
