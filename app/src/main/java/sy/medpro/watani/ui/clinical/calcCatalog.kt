/** الكتالوج كمفهرس بالمفتاح — كل مفتاح مرة واحدة فقط. */
val calcCatalog: Map<String, CalcCatalogEntry> = calcCatalogEntries.associateBy { it.key }

/** فئة أي أداة من الكتالوج؛ مفتاح غير معروف يقع في آخر فئة كي لا تختفي أداة من الدليل أبدًا. */
fun calcCatalogCategoryOf(key: String): String =
    calcCatalog[key]?.categoryTitleAr ?: CALC_CATEGORY_TITLES.last()

/** الوصف القصير المعروض في صف الدليل لأي أداة. */
fun calcCatalogDescriptionOf(key: String): String =
    calcCatalog[key]?.shortDescriptionAr.orEmpty()

/** عدّاد أدوات فئة ما كما سيظهر في شريحة الفئة بشاشة الدليل. */
fun calcCatalogCountOf(categoryTitleAr: String): Int =
    calcCatalogEntries.count { it.categoryTitleAr == categoryTitleAr }
